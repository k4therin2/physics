"""V5 step 2: substitute each k = 0 residual mode (as an exact coordinate transformation of FRW + arbitrary first-order
fields, amplitude eps*s, i.e. counted as FIRST order) into the complete map through second order (C2 machinery, rebuilt
in los_v5.py with first-order omega, h) and compare with the untransformed map.
Everything that is coordinate dependent is transformed consistently:
  fields (gauge.transform), observer EVENT (the clock condition is a scalar statement => same event, new coordinates),
  observer label (x_o(eta->0) = 0 is preserved by every generator below), emission surface T_phys = T_* (scalar; C2's
  emission formulas re-evaluated with the new dT), direction map (C2's canonical Gram-Schmidt triad in the NEW coordinates),
  ray functionals k1, Dx1 (re-derived from their defining integrals with the new fields).
Claim tested:  Delta L1 = 0 and  Delta L2 = (omega x n).d_n L1 + const + int D(W)  with omega constant (a rigid rotation of
the sky, generated by the canonical triad), const direction independent (drops from Theta for l >= 1) and W a total
derivative along the background ray whose boundary values cancel the endpoint terms."""
