def verify(out, W_list, label):
    """fit omega (rotation) and coefficients of the total-derivative ansatz; then the boundary check.  Prints verdict."""
    sol, W, resid = match_rotation(out, W_list)
    print('  [%s] fit of  R_ray = rot(omega) + D W :' % label, sol)
    if not sol:
        print('  NO SOLUTION; residual terms:', len(sp.Add.make_args(resid))); return False, None
    sol = sol[0]
    om = sp.symbols('omega1:4')
    Ws = sp.expand(W.subs(sol))
    bobs = unit_rules(sp.expand(out['obs'] + eval_where(Ws, 'obs')))
    bemi = unit_rules(sp.expand(out['emi'] - eval_where(Ws, 'emi')))
    free = [u for u in list(om) + list(sp.symbols('w0:%d' % len(W_list or []))) if u not in sol]
    print('  rotation vector omega =', [sol.get(o_, o_) for o_ in om], '; W =', sp.factor(Ws) if len(str(Ws)) < 300 else '(%d terms)' % len(sp.Add.make_args(Ws)))
    print('  boundary  obs + W(obs) =', bobs, ';  emi - W(emi) =', bemi)
    has_f = lambda e: bool(placeholders(e))
    ok = (not bobs.has(*n)) and (not bemi.has(*n)) and not has_f(bemi)   # obs fields = monopole; emi must be field-free
    print('  VERDICT [%s]: Delta Theta2 = pure rotation of Theta1 (+ monopole):' % label, ok)
    return ok, sol
