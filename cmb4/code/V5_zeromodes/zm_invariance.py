def placeholders(e):
    """map field atoms to symbols so that linear algebra in their coefficients is possible."""
    atoms = [a for a in e.atoms(sp.Derivative) if is_field(a.expr)] + [a for a in e.atoms(sp.core.function.AppliedUndef) if is_field(a)]
    return atoms

def match_rotation(out, extra_W=None):
    """Solve R_ray - rot(omega) = Dtot(W) with W = sum of ansatz terms (each a sympy expr in fields at the ray point, times
    unknown coefficients); then check obs/emi boundary terms: obs + W(obs) and emi - W(emi) must be direction-independent
    constants (monopole) => removed by normalisation."""
    om = sp.symbols('omega1:4')
    unknowns = list(om)
    W = sp.Integer(0)
    if extra_W:
        cs = sp.symbols('w0:%d' % len(extra_W)); unknowns += list(cs)
        W = sum(c_*w_ for c_, w_ in zip(cs, extra_W))
    DW = sp.diff(W, eta) - sum(n[i]*sp.diff(W, COORD[i]) for i in range(3))
    resid = unit_rules(sp.expand(out['R'] - out['rot'] - eval_where(sp.expand(DW), 'ray')))
    ats = placeholders(resid)
    reps = {a: sp.Dummy() for a in ats}
    r2 = sp.expand(resid.subs(reps))
    eqs = []
    gens = list(reps.values()) + list(n) + [eta, eta_o, eta_s]
    P = sp.Poly(r2, *gens)
    eqs = [c_ for c_ in P.coeffs()]
    sol = sp.solve(eqs, unknowns, dict=True)
    # IMPORTANT: sympy's solve silently drops equations free of the unknowns; verify the residual explicitly.
    good = []
    for so in sol:
        full = {u: so.get(u, 0) for u in unknowns}   # unfixed unknowns set to 0
        chk = unit_rules(sp.expand(r2.subs(full)))
        if chk == 0: good.append(full)
    if not sol:
        chk = r2
    if sol and not good:
        print('  (solve returned', sol, 'but the residual does not vanish:', len(sp.Add.make_args(chk)), 'terms)')
    return good, W, resid

