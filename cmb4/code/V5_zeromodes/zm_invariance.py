def trunc_s(e):
    e = sp.expand(e)
    return sp.Add(*[t for t in sp.Add.make_args(e) if sp.degree(t, s) <= 1])
# generic L with the emission shifts written out
def with_emission(e):
    return sp.expand(sp.expand(e).subs(de2, em[de2]).subs(de1, em[de1]))
LG = {m: [(w, with_emission(e)) for w, e in D5['L'][m]] for m in (1, 2)}

def is_field(a):
    return isinstance(a, sp.core.function.AppliedUndef) and len(a.args) == 4
def eval_where(e, where):
    """evaluate explicit coordinates at the 'where' point keeping field placeholders (fields are implicitly there)."""
    e = sp.expand(e)
    reps = {}
    for a in e.atoms(sp.Derivative):
        if is_field(a.expr): reps[a] = sp.Dummy()
    e = e.xreplace(reps)
    reps2 = {a: sp.Dummy() for a in e.atoms(sp.core.function.AppliedUndef) if is_field(a)}
    e = e.xreplace(reps2)
    if where == 'ray': e = e.subs({x: n[0]*(eta_o - eta), y: n[1]*(eta_o - eta), z: n[2]*(eta_o - eta)}, simultaneous=True)
    elif where == 'obs': e = e.subs({x: 0, y: 0, z: 0, eta: eta_o}, simultaneous=True)
    elif where == 'emi': e = e.subs({x: n[0]*(eta_o - eta_s), y: n[1]*(eta_o - eta_s), z: n[2]*(eta_o - eta_s), eta: eta_s}, simultaneous=True)
    inv = {v_: k_ for k_, v_ in list(reps.items()) + list(reps2.items())}
    return sp.expand(e.xreplace(inv))
def full_eval(e, where):
    """explicit function of coordinates only (no fields): evaluate at where (ray: as a function of eta)."""
    if where == 'ray': return sp.expand(e.subs({x: n[0]*(eta_o - eta), y: n[1]*(eta_o - eta), z: n[2]*(eta_o - eta)}, simultaneous=True))
    if where == 'obs': return sp.expand(e.subs({x: 0, y: 0, z: 0, eta: eta_o}, simultaneous=True))

def observer_event(E, Xs):
    """new coordinates of the observer event; old event = (etabar_o + eps deta_o1 + eps^2 deta_o2/2, eps dxo1 + eps^2 dxo2/2)."""
    old = [eta_o + eps*deta_o1 + eps**2*deta_o2/2] + [eps*dxo1[i] + eps**2*dxo2[i]/2 for i in range(3)]
    Delta = [sp.expand(E - eta)] + [sp.expand(Xs[i] - X[i+1]) for i in range(3)]
    new = list(old)
    for it in range(N+1):
        rep = dict(zip(X, new))
        new = [sp.expand(old[a] - Delta[a].subs(rep, simultaneous=True)) for a in range(4)]
        new = [sp.expand(sp.series(t, eps, 0, N+1).removeO()) for t in new]
    c = lambda e_, k: trunc_s(sp.expand(e_).coeff(eps, k))
    return {deta_o1: c(new[0], 1), deta_o2: 2*c(new[0], 2), **{dxo1[i]: c(new[i+1], 1) for i in range(3)},
            **{dxo2[i]: 2*c(new[i+1], 2) for i in range(3)}}, sp.expand(new[0].coeff(eps, 0))

def rot_n(e, where, om):
    """(om x n).d_n acting on an L-piece (fields on the background ray at x = n(eta_o - eta))."""
    dn = [om[1]*n[2] - om[2]*n[1], om[2]*n[0] - om[0]*n[2], om[0]*n[1] - om[1]*n[0]]
    lev = {'ray': eta_o - eta, 'emi': eta_o - eta_s, 'obs': 0}[where]
    return sp.expand(sum(dn[i]*(sp.diff(e, n[i]) + lev*sp.diff(e, COORD[i])) for i in range(3)))

def run(name, E, Xs, W_ansatz=None, verbose=True, naive=False, Kextra=None):
    print('\n================ generator:', name, '================'); print('  eta_old =', E, ';  x_old =', Xs)
    new = gauge.transform(E, Xs)
    sub = gauge.substitution(new, s)
    zm = {k_: sp.expand(v_).coeff(s, 1).subs(eps, 0) for k_, v_ in sub.items() if str(k_.func)[-1] == '1'}
    zm = {k_: sp.expand(sp.expand(v_).coeff(s, 1)) for k_, v_ in sub.items() if str(k_.func).endswith('1')}
    zm = {k_: v_.xreplace({f_: 0 for f_ in v_.atoms(sp.core.function.AppliedUndef) if f_.args == X}) for k_, v_ in zm.items()}
    if naive:   # NEGATIVE CONTROL: superpose the zero mode at first order but do NOT transform the first-order fields
        sub = {k_: (k_ + s*zm[k_] if k_ in zm else k_) for k_ in sub}
        print('  NAIVE superposition (no cross terms with first-order fields)')
    print('  induced first-order zero-mode fields (coefficient of s):')
    for k_, v_ in zm.items():
        if v_ != 0: print('     %-6s = %s' % (str(k_.func), sp.factor(v_)))
    # literal Poisson-gauge conditions on the zero mode: d_i om_i = 0, h_ii = 0, d_i h_ij = 0
    omz = [zm[F('om_%d_1' % i)] for i in (1, 2, 3)]
    hz = [[zm[F('h_%d%d_1' % tuple(sorted((i, j))))] if (i, j) != (3, 3) else -(zm[F('h_11_1')] + zm[F('h_22_1')]) for j in (1, 2, 3)] for i in (1, 2, 3)]
    divom = sp.simplify(sum(sp.diff(omz[i], COORD[i]) for i in range(3)))
    divh = [sp.simplify(sum(sp.diff(hz[i][j], COORD[i]) for i in range(3))) for j in range(3)]
    print('  Poisson conditions on zero mode: div omega =', divom, '; div h =', divh)
    # observer event in the new coordinates
