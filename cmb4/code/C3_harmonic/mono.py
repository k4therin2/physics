def P_mono(sigma2, k0):
    """returns a callable P(k) as a delta-function weight: use the substitution rules above instead of evaluating it."""
    return dict(sigma2=sigma2, k0=k0, P_norm=2 * np.pi ** 2 * sigma2 / k0 ** 2)


def C11_mono(l, sigma2, DeltaA_k0, DeltaAp_k0=None):
    DeltaAp_k0 = DeltaA_k0 if DeltaAp_k0 is None else DeltaAp_k0
    return 4 * np.pi * sigma2 * DeltaA_k0 * np.conj(DeltaAp_k0)


def lmax_rule(X):
    return int(X + 10 * X ** (1 / 3) + 10)


def test_mono_normalisation(verbose=True):
    """<zeta^2> = sigma^2 with P = 2 pi^2 sigma^2 delta(k-k0)/k0^2: check (1/2pi^2) int k^2 dk P = sigma^2 via a narrow Gaussian delta."""
    k0, sigma2, eps = 1.3, 0.7, 1e-3
    k = np.linspace(k0 - 10 * eps, k0 + 10 * eps, 20001)
    delta = np.exp(-(k - k0) ** 2 / (2 * eps ** 2)) / (np.sqrt(2 * np.pi) * eps)
    P = 2 * np.pi ** 2 * sigma2 * delta / k0 ** 2
    val = np.trapezoid(k ** 2 * P, k) / (2 * np.pi ** 2)
    if verbose:
        print("  %-80s rel err = %.2e" % ("monochromatic normalisation <zeta^2> = sigma^2", abs(val - sigma2) / sigma2))
    return abs(val - sigma2) / sigma2


if __name__ == "__main__":
    test_mono_normalisation()
